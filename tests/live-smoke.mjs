// Smoke test against the live deployment (Netlify + Supabase cloud). Usage: BASE=https://federations-mvp.netlify.app node tests/live-smoke.mjs
import { chromium } from 'playwright'
const BASE = process.env.BASE ?? 'https://federations-mvp.netlify.app'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] }); const ctx = await b.newContext({ viewport: { width: 1360, height: 900 }, locale: 'el-GR' })
const p = await ctx.newPage(); const errors = []
p.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
p.on('pageerror', e => errors.push(e.message))
const shot = (n) => p.screenshot({ path: `../reports/screens/live-${n}.png`, fullPage: false })
await p.goto(BASE + '/login'); await p.waitForSelector('text=admin@esna-demo.gr')
await p.click('text=admin@esna-demo.gr')
await p.waitForURL(u => !u.pathname.startsWith('/login'), { timeout: 20000 })
await p.waitForSelector('.font-display.tabular-nums', { timeout: 20000 }); await p.waitForTimeout(1500); await shot('dashboard')
console.log('dashboard stats:', await p.$$eval('.font-display.tabular-nums', els => els.map(e => e.textContent.trim()).slice(0, 4)))
await p.goto(BASE + '/licenses?status=queue'); await p.waitForSelector('table', { timeout: 20000 }); await p.waitForTimeout(1000)
console.log('queue rows:', await p.$$eval('table tbody tr', r => r.length)); await shot('licenses')
await p.goto(BASE + '/finance'); await p.waitForSelector('table', { timeout: 20000 }); await p.waitForTimeout(1000); await shot('finance')
await p.goto(BASE + '/f/esna/c/paidon-2026-27'); await p.waitForSelector('table', { timeout: 20000 }); await p.waitForTimeout(1000); await shot('public')
console.log('public standings rows:', await p.$$eval('table tbody tr', r => r.length))
await p.goto(BASE + '/competitions'); await p.getByText('Πρωτάθλημα Παίδων ΕΣΝΑ 2026-27').first().click()
await p.getByRole('button', { name: 'Ομάδες' }).click()
await p.locator('tr[data-entry]').first().getByRole('button', { name: 'Σύνθεση' }).click()
await p.waitForSelector('[data-roster] tbody tr', { timeout: 20000 }); await p.waitForTimeout(800)
console.log('roster rows:', await p.locator('[data-roster] tbody tr').count(), 'ineligible:', await p.locator('[data-roster]').getByText('Μη επιλέξιμος').count()); await shot('roster')
await p.goto(BASE + '/f/esna/c/kypello-paidon-2026-27'); await p.waitForSelector('[data-bracket-match]', { timeout: 20000 })
console.log('public bracket matches:', await p.locator('[data-bracket-match]').count()); await shot('bracket')
await p.goto(BASE + '/f/osd/c/diasyllogikoi-k16-2027'); await p.waitForSelector('table', { timeout: 20000 }); await p.waitForTimeout(800)
console.log('public meet rows:', await p.$$eval('tbody tr', r => r.length), 'masked:', /\S\. \S\./.test(await p.locator('body').innerText())); await shot('meet')
console.log('console errors:', errors.length, errors.slice(0, 5))
await b.close()
